  /* ---------------- 公共工具 ---------------- */
  function has(sid) { return !!BANK[sid]; }
  function cleanTitle(t) {
    return String(t || '').replace(/[（(][^)）]*[)）]/g, '')
      .replace(/第[一二三四五六七八九十\d]+[章节单元][·:：\s]*/g, '')
      .replace(/^\d+\s*/, '').replace(/\s+/g, '').trim();
  }
  /** 找出与目录标题最贴合的章节（取最长命中，避免"气候"抢走"世界的气候"） */
  function matchChapter(sid, title) {
    var bank = BANK[sid];
    if (!bank) return null;
    var t = cleanTitle(title), best = null, bestLen = 0;
    bank.chapters.forEach(function (c) {
      var k = cleanTitle(c.k);
      if (!k) return;
      if (t.indexOf(k) >= 0 || k.indexOf(t) >= 0) {
        if (k.length > bestLen) { best = c; bestLen = k.length; }
      }
    });
    return best;
  }
  function uniq(a) {
    var o = {}, r = [];
    a.forEach(function (x) { if (x && !o[x]) { o[x] = 1; r.push(x); } });
    return r;
  }
  function pick(arr, seed) { return arr[seed % arr.length]; }

  /** 生成本课概念词：命中章节优先，其次用标题汉字找相关词，最后按学科常用词兜底 */
  function words(sid, title, seed) {
    var bank = BANK[sid];
    if (!bank) return [];
    var chap = matchChapter(sid, title), names = [], keys = Object.keys(bank.dict), i, ch;
    if (chap) names = chap.t.slice();
    if (!names.length) {
      var t = cleanTitle(title);
      for (i = 0; i < t.length && names.length < 5; i++) {
        ch = t.charAt(i);
        for (var j = 0; j < keys.length; j++) {
          if (keys[j].indexOf(ch) >= 0 && names.indexOf(keys[j]) < 0) { names.push(keys[j]); break; }
        }
      }
    }
    if (names.length < 5) {
      for (i = 0; i < keys.length && names.length < 5; i++) {
        var w = keys[(seed + i * 7) % keys.length];
        if (names.indexOf(w) < 0) names.push(w);
      }
    }
    return uniq(names).slice(0, 5).map(function (n) {
      var d = bank.dict[n] || { p: '', m: '本课重要概念，对照课本理解' };
      return n + '|' + d.p + '|' + d.m;
    });
  }

  /** 生成跟读句：先读本章概念，再读学科通用学习方法 */
  function lines(sid, title, seed, wordArr) {
    var bank = BANK[sid];
    if (!bank) return [];
    var out = [], i;
    var ws = (wordArr || []).slice(0, 3).map(function (w) { return w.split('|'); });
    ws.forEach(function (a) {
      out.push([a[0], a[1] || '', a[2] || ''].join('|'));
    });
    var r = bank.read, start = seed % r.length;
    for (i = 0; i < 4; i++) out.push(r[(start + i) % r.length]);
    return out;
  }

  /** 生成通关题：概念释义匹配 + 学科通用辨析题 */
  function quiz(sid, title, seed, wordArr, poolArr) {
    var bank = BANK[sid];
    if (!bank) return [];
    var ws = (wordArr || []).map(function (w) { return w.split('|'); });
    var keys = Object.keys(bank.dict), out = [], i, j;
    function shuffle(a) {
      var b = a.slice(), k, t;
      for (k = b.length - 1; k > 0; k--) { j = Math.floor(Math.random() * (k + 1)); t = b[k]; b[k] = b[j]; b[j] = t; }
      return b;
    }
    for (i = 0; i < Math.min(4, ws.length); i++) {
      var term = ws[i][0], mean = ws[i][2];
      if (!term || !mean) continue;
      var wrong = [];
      for (j = 0; j < poolArr.length && wrong.length < 3; j++) {
        var other = (poolArr[j] || '').split('|');
        if (other[0] !== term && other[2] && other[2] !== mean) wrong.push(other[2]);
      }
      for (j = 0; j < keys.length && wrong.length < 3; j++) {
        var m = bank.dict[keys[(seed + i * 5 + j) % keys.length]].m;
        if (m !== mean) wrong.push(m);
      }
      wrong = uniq(wrong).slice(0, 3);
      if (wrong.length < 3) continue;
      var opts = shuffle([mean].concat(wrong));
      out.push([term.replace(/\|/g, '') + ' 指的是什么？', opts.join(','), opts.indexOf(mean),
        term + '（' + (ws[i][1] || '') + '）：' + mean + '。再读一遍记一记。'].join('|'));
    }
    /* 学科通用辨析题全部加入，确保每个单元至少有 5 道题 */
    var qb = bank.quiz, st = seed % qb.length;
    for (i = 0; i < qb.length; i++) {
      var q = qb[(st + i) % qb.length];
      out.push([q.q, q.o.join(','), q.a, q.e].join('|'));
    }
    return uniq(out).slice(0, 8);
  }

